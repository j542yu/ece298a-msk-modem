`default_nettype none

module transmit (
  input wire in,
  output reg [7:0] out,
  input wire clk,
  input wire rst_n,
  input wire enable
);

// Registers
reg curr;
reg [2:0] sample;

wire [11:0] wangle;
wire [7:0] IQ;
reg [11:0] angle;

assign wangle = angle;

cos_lut inst (.angle(wangle), .cos(IQ));

assign out = IQ;

// 8 samples per symbol
// Phase accumulator
always @(posedge clk or negedge rst_n) begin
  if (!rst_n) begin
    sample <= 3'b111;
    angle <= 5'b0;
  end else if (enable) begin
    if (sample == 3'b111) curr <= in;
    
    sample <= sample + 1;
    
    angle <= angle + {curr << 1} - 1; // phase + 2*curr -1
  end
end

endmodule

